#include "exteria_folders.h"
#include "test_util.h"

int main(void) {
    exteria_folder_rules rules;
    exteria_dialog_row dialog;
    exteria_peer_ref peers[2];
    memset(&rules, 0, sizeof(rules));
    memset(&dialog, 0, sizeof(dialog));
    memset(peers, 0, sizeof(peers));
    dialog.peer_kind = 1;
    dialog.peer_id = 42;
    dialog.kind = EXTERIA_DIALOG_USER;
    CHECK(!exteria_folder_contains(NULL, &dialog));
    CHECK(!exteria_folder_contains(&rules, NULL));
    CHECK(!exteria_folder_contains(&rules, &dialog));
    rules.flags = EXTERIA_FOLDER_CONTACTS;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    dialog.contact = 1;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.contact = 0;
    dialog.saved = 1;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.saved = 0;
    rules.flags = EXTERIA_FOLDER_NON_CONTACTS;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.kind = EXTERIA_DIALOG_BOT;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    rules.flags = EXTERIA_FOLDER_BOTS;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.kind = EXTERIA_DIALOG_GROUP;
    rules.flags = EXTERIA_FOLDER_GROUPS;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.kind = EXTERIA_DIALOG_CHANNEL;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    rules.flags = EXTERIA_FOLDER_CHANNELS | EXTERIA_FOLDER_SKIP_READ | EXTERIA_FOLDER_SKIP_MUTED;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    dialog.unread_mark = 1;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.muted = 1;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    dialog.mentions = 1;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.unread_mark = 0;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.folder_id = 1;
    rules.flags |= EXTERIA_FOLDER_SKIP_ARCHIVED;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    peers[0].kind = 1;
    peers[0].id = 42;
    rules.included = peers;
    rules.included_count = 1;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.peer_kind = 3;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    peers[0].kind = 3;
    CHECK(exteria_folder_contains(&rules, &dialog));
    rules.excluded = peers;
    rules.excluded_count = 1;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    rules.pinned = peers;
    rules.pinned_count = 1;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    CHECK_EQ_INT(exteria_folder_pin_index(&rules, &dialog), 0);
    rules.excluded_count = 0;
    rules.included_count = 0;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.folder = 1;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    dialog.folder = 0;
    rules.pinned_count = 0;
    CHECK(exteria_folder_pin_index(&rules, &dialog) == SIZE_MAX);
    rules.included_count = EXTERIA_FOLDER_PEERS_MAX + 1;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    rules.included_count = 1;
    rules.included = NULL;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    rules.included = peers;
    peers[0].self = 1;
    dialog.saved = 1;
    CHECK(exteria_folder_contains(&rules, &dialog));
    dialog.saved = 0;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    rules.included_count = 0;
    dialog.folder_id = 0;
    dialog.community = 1;
    rules.flags = 31;
    CHECK(exteria_folder_contains(&rules, &dialog));
    rules.flags = EXTERIA_FOLDER_GROUPS;
    CHECK(!exteria_folder_contains(&rules, &dialog));
    return test_finish("test_folders");
}
