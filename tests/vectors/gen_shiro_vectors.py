#!/usr/bin/env python3
"""writes tests/core/shiro_vectors.h from independent implementations (hashlib, hmac, cryptography)"""
import hashlib, hmac, sys
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives import serialization

def pattern(n, seed):
    return bytes((i * 7 + seed) & 0xFF for i in range(n))

def arr(b):
    return "{" + ", ".join("0x%02x" % x for x in b) + "}" if b else "{0}"

def raw_priv(b):
    return X25519PrivateKey.from_private_bytes(b)

def pub_of(priv):
    return raw_priv(priv).public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)

out = []
out.append("/* generated by tests/vectors/gen_shiro_vectors.py, do not edit */\n")
out.append("#include <stddef.h>\n#include <stdint.h>\n")

out.append("typedef struct { size_t key_len, data_len, out_len; uint8_t key[32]; uint8_t expect[32]; } blake_vector;")
out.append("static const blake_vector blake_vectors[] = {")
for key_len in (0, 16, 32):
    for data_len in (0, 1, 63, 64, 65, 127, 128, 129, 1000):
        for out_len in (16, 32):
            key = pattern(key_len, 1)
            d = hashlib.blake2s(pattern(data_len, 5), key=key, digest_size=out_len).digest()
            out.append("    {%d, %d, %d, %s, %s}," % (key_len, data_len, out_len, arr(key.ljust(32, b"\0")), arr(d.ljust(32, b"\0"))))
out.append("};")

out.append("typedef struct { size_t key_len, data_len; uint8_t key[64]; uint8_t expect[32]; } hmac_vector;")
out.append("static const hmac_vector hmac_vectors[] = {")
for key_len in (0, 32, 33, 64):
    for data_len in (0, 1, 32, 33, 64, 65, 300):
        key = pattern(key_len, 9)
        d = hmac.new(key, pattern(data_len, 11), hashlib.blake2s).digest()
        out.append("    {%d, %d, %s, %s}," % (key_len, data_len, arr(key.ljust(64, b"\0")), arr(d)))
out.append("};")

# RFC 7748 section 6.1
a = bytes.fromhex("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a")
b = bytes.fromhex("5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb")
assert pub_of(a).hex() == "8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a"
assert pub_of(b).hex() == "de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f"
shared = raw_priv(a).exchange(X25519PublicKey.from_public_bytes(pub_of(b)))
assert shared.hex() == "4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742"
out.append("typedef struct { uint8_t priv[32], pub[32], peer[32], shared[32]; } x25519_vector;")
out.append("static const x25519_vector x25519_vectors[] = {")
pairs = [(a, b)]
for i in range(6):
    pairs.append((pattern(32, 20 + i), pattern(32, 90 + i)))
for pa, pb in pairs:
    pk = pub_of(pa)
    peer = pub_of(pb)
    sh = raw_priv(pa).exchange(X25519PublicKey.from_public_bytes(peer))
    out.append("    {%s, %s, %s, %s}," % (arr(pa), arr(pk), arr(peer), arr(sh)))
out.append("};")

out.append("typedef struct { size_t ad_len, len; uint8_t key[32], nonce[12]; uint8_t ad[64], plain[200], cipher[200], tag[16]; } aead_vector;")
out.append("static const aead_vector aead_vectors[] = {")
for ad_len, ln in ((0, 0), (0, 1), (12, 0), (12, 32), (16, 64), (1, 129), (32, 148)):
    key, nonce = pattern(32, 3), pattern(12, 4)
    ad, pt = pattern(ad_len, 6), pattern(ln, 8)
    ct = ChaCha20Poly1305(key).encrypt(nonce, pt, ad)
    out.append("    {%d, %d, %s, %s, %s, %s, %s, %s}," % (ad_len, ln, arr(key), arr(nonce), arr(ad.ljust(64, b"\0")), arr(pt.ljust(200, b"\0")),
                                                         arr(ct[:-16].ljust(200, b"\0")), arr(ct[-16:])))
out.append("};")
sys.stdout.write("\n".join(out) + "\n")
