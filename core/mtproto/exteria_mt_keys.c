static size_t put_tl_bytes(uint8_t *out, const uint8_t *data, size_t len) {
    size_t pos = 0, total;
    if (len < 254) {
        out[pos++] = (uint8_t)len;
    } else {
        out[pos++] = 254;
        out[pos++] = (uint8_t)len;
        out[pos++] = (uint8_t)(len >> 8);
        out[pos++] = (uint8_t)(len >> 16);
    }
    for (total = 0; total < len; ++total) out[pos++] = data[total];
    while (pos % 4) out[pos++] = 0;
    return pos;
}

exteria_status exteria_mt_rsa_fingerprint(const uint8_t *n, size_t n_len, uint32_t e, uint64_t *out) {
    uint8_t buf[512];
    uint8_t ebytes[4];
    uint8_t digest[EXTERIA_SHA1_LEN];
    size_t pos, elen = 0;
    exteria_status s;
    *out = 0;
    if (!n || n_len == 0 || n_len > 256 || e == 0) return EXTERIA_E_ARG;
    ebytes[0] = (uint8_t)(e >> 24);
    ebytes[1] = (uint8_t)(e >> 16);
    ebytes[2] = (uint8_t)(e >> 8);
    ebytes[3] = (uint8_t)e;
    while (elen < 3 && ebytes[elen] == 0) ++elen;
    pos = put_tl_bytes(buf, n, n_len);
    pos += put_tl_bytes(buf + pos, ebytes + elen, 4 - elen);
    s = exteria_sha1_one(buf, pos, digest);
    if (s != EXTERIA_OK) return s;
    *out = exteria_get_u64le(digest + 12);
    return EXTERIA_OK;
}

const exteria_mt_rsa_key *exteria_mt_find_key(const exteria_mt_rsa_key *keys, size_t count, uint64_t fingerprint) {
    size_t i;
    for (i = 0; i < count; ++i) {
        if (keys[i].fingerprint == fingerprint) return &keys[i];
    }
    return NULL;
}
