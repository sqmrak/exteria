#!/usr/bin/env python3
"""makes resources/localization/sqmrak.lproj from the russian texts: all lowercase, a few stretched words, a few emoticons.

run it again after the russian strings change; the output is never edited by hand."""
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "resources/localization/ru.lproj/Localizable.strings"
TARGET = ROOT / "resources/localization/sqmrak.lproj/Localizable.strings"

ENTRY = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";\s*$')
CYRILLIC = re.compile("[а-яА-ЯёЁ]")
# format specifiers and escapes stay as they are, since a changed letter in them changes what the string means
PROTECTED = re.compile(r'(%(?:\d+\$)?[-+ 0#]*\d*(?:\.\d+)?(?:ll|l|h|z|q)?[@dDuUxXfeEgGcCsSpoi%]|\\.)')

# whole words that get a longer vowel, and nothing else does
STRETCH = {
    "печатает": "печаааатает",
    "печатают": "печаааатают",
    "записывает": "записываааает",
    "привет": "приииивет",
    "спасибо": "спасииибо",
    "готово": "готоооово",
    "ошибка": "ошииибка",
    "ура": "урааа",
}
STRETCH_RE = re.compile(r"(?<![а-яё])(" + "|".join(STRETCH) + r")(?![а-яё])")

# the kinds of key that may end in an emoticon: explanations, empty screens and failures, a third of the explanations and all the other two
EXPLAINS = (".info", ".hint", ".notice", ".message", ".footer", ".wait")
EMOTICONS = {"info": [":3", ":D", ":P", ":3"], "empty": [":3", ":3", ":D"], "failed": [":#", ":P", ":#"]}


def lower(value):
    parts = PROTECTED.split(value)
    return "".join(part if index % 2 else part.lower() for index, part in enumerate(parts))


def kind_of(key, value):
    if not CYRILLIC.search(value) or "%" in value or len(value) < 22:
        return None
    if key.endswith(".empty"):
        return "empty"
    if key.endswith(".failed"):
        return "failed"
    if key.endswith(EXPLAINS) and zlib.crc32(key.encode()) % 3 == 0:
        return "info"
    return None


def with_emoticon(key, value, kind):
    options = EMOTICONS[kind]
    mark = options[zlib.crc32(key.encode()) % len(options)]
    trimmed = value.rstrip()
    if trimmed.endswith(":"):
        return value
    if trimmed.endswith("."):
        trimmed = trimmed[:-1]
    return trimmed + " " + mark


# addresses and model names that the person copies as they are
KEEP = {"tr.llm.url.hint", "tr.llm.model.default"}


def convert(key, value):
    if key in KEEP:
        return value
    out = STRETCH_RE.sub(lambda match: STRETCH[match.group(1)], lower(value))
    kind = kind_of(key, value)
    return with_emoticon(key, out, kind) if kind else out


def main():
    lines = SOURCE.read_text(encoding="utf-8").split("\n")
    out = ["/* generated by tools/make_sqmrak_strings.py from the russian texts, do not edit by hand */"]
    for line in lines:
        match = ENTRY.match(line)
        if match:
            out.append('"%s" = "%s";' % (match.group(1), convert(match.group(1), match.group(2))))
        elif line.strip().startswith("/*"):
            out.append(line.lower())
        else:
            out.append(line)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(out), encoding="utf-8")
    print("wrote", TARGET.relative_to(ROOT), len(out), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
