import java.text.*;
import java.util.*;

/** writes python/shim/dexvm/jcollate_data.py: the collation elements of the default rules of the jdk, for every char the rules map.
 *  run: java tools/GenCollation.java > python/shim/dexvm/jcollate_data.py   (a jdk 17 or newer) */
public class GenCollation {
    public static void main(String[] args) {
        RuleBasedCollator rb = (RuleBasedCollator) Collator.getInstance(Locale.US);
        System.out.println("\"\"\"collation elements of the default rules of the jdk (generated by tools/GenCollation.java, do not edit): code point -> ((primary, secondary, tertiary), ...)\"\"\"");
        System.out.println();
        System.out.println("ELEMENTS = {");
        for (int c = 0; c < 0x10000; c++) {
            if (c >= 0xd800 && c < 0xe000) continue;
            CollationElementIterator it = rb.getCollationElementIterator(String.valueOf((char) c));
            StringBuilder sb = new StringBuilder();
            int o, count = 0;
            boolean unmapped = false;
            while ((o = it.next()) != CollationElementIterator.NULLORDER) {
                int p = CollationElementIterator.primaryOrder(o);
                if (count == 0 && p == 0x7fff) unmapped = true;
                sb.append(String.format("(%d,%d,%d),", p, CollationElementIterator.secondaryOrder(o), CollationElementIterator.tertiaryOrder(o)));
                count++;
            }
            if (unmapped) continue;
            System.out.println("    " + c + ": (" + sb + "),");
        }
        System.out.println("}");
        System.out.println();
        StringBuilder r = new StringBuilder();
        for (char ch : rb.getRules().toCharArray()) {
            if (ch == '\\' || ch == '"') r.append('\\').append(ch);
            else if (ch < 32 || ch > 126) r.append(String.format("\\u%04x", (int) ch));
            else r.append(ch);
        }
        System.out.println("RULES = \"" + r + "\"");
    }
}
