"""java.text.Collator, RuleBasedCollator, CollationKey and CollationElementIterator

the default rules are the collation elements the jdk builds from its default rules (jcollate_data, generated by tools/GenCollation.java), and
compare() is the algorithm of RuleBasedCollator.compare: elements are compared in lock step, an element without a primary weight is only a
secondary difference, and the first secondary or tertiary difference decides when the primaries agree. a collator made from rules of a
program starts from nothing: characters the rules do not mention sort after those they do, by code point. locales have no tailorings of
their own here"""

import unicodedata

from . import runtime
from .api import host_class, jmethod, jstatic, lookup_host
from .jcollate_data import ELEMENTS, RULES
from .jlang import Object, jstr
from .jutil import check_nonnull

NULLORDER = -1
_MISSING = object()


def _java_compare(a, b):
    for x, y in zip(a, b):
        if x != y:
            return ord(x) - ord(y)
    return len(a) - len(b)


def _order(element):
    p, s, t = element
    return runtime.wrap32((p << 16) | (s << 8) | t)


def _elements(text, table, contractions, decomposition, decompose_unmapped=False):
    if decomposition == 1:
        text = unicodedata.normalize("NFD", text)
    elif decomposition == 2:
        text = unicodedata.normalize("NFKD", text)
    out = []
    i = 0
    n = len(text)
    while i < n:
        matched = False
        if contractions:
            for length in range(min(contractions, n - i), 1, -1):
                found = table.get(text[i:i + length])
                if found is not None:
                    out.extend(found)
                    i += length
                    matched = True
                    break
        if matched:
            continue
        c = text[i]
        found = table.get(c)
        if found is None:
            decomposed = unicodedata.normalize("NFD", c)
            if decomposed != c and decompose_unmapped:
                out.extend(_elements(decomposed, table, contractions, 0, True))
                i += 1
                continue
            found = ((0x7FFF, 0, 0), (ord(c), 0, 0))
        out.extend(found)
        i += 1
    return out


class _Table:
    def __init__(self, mapping, rules, decompose=True):
        self.mapping, self.rules, self.decompose = mapping, rules, decompose
        self.contractions = max((len(k) for k in mapping if isinstance(k, str)), default=1)
        self.contractions = self.contractions if self.contractions > 1 else 0


def _default_table():
    mapping = {chr(code): elements for code, elements in ELEMENTS.items()}
    return _Table(mapping, RULES, False)


_DEFAULT = None


def default_table():
    global _DEFAULT
    if _DEFAULT is None:
        _DEFAULT = _default_table()
    return _DEFAULT


def _parse_error(message, rules, position):
    error = runtime.make_throwable(lookup_host("java.text.ParseException").py, message)
    error._offset = position
    raise error


def build_table(rules):
    """the collation elements of a rule string: relations < ; , = after a reset & and the characters (or quoted strings) they relate"""
    tokens = []
    i, n = 0, len(rules)
    while i < n:
        c = rules[i]
        if c.isspace():
            i += 1
        elif c in "<;,=&@!":
            tokens.append(("op", c, i))
            i += 1
        elif c == "'":
            j = i + 1
            text = []
            while j < n and rules[j] != "'":
                text.append(rules[j])
                j += 1
            if not text and j < n:
                text = ["'"]
            tokens.append(("str", "".join(text), i))
            i = j + 1
        else:
            j = i
            text = []
            while j < n and not rules[j].isspace() and rules[j] not in "<;,=&@!'":
                text.append(rules[j])
                j += 1
            tokens.append(("str", "".join(text), i))
            i = j
    nodes = []          # [text, relation to the node before: 0 primary, 1 secondary, 2 tertiary, 3 equal]
    index = {}
    pos = -1
    pending_rel = None
    reset_pending = False
    k = 0
    while k < len(tokens):
        kind, value, where = tokens[k]
        k += 1
        if kind == "op":
            if value == "&":
                reset_pending = True
            elif value in "@!":
                pass
            else:
                if reset_pending:
                    _parse_error("missing chars (=,;<&): " + rules[where:].strip(), rules, where)
                pending_rel = "<;,=".index(value)
            continue
        if reset_pending:
            reset_pending = False
            ref = value
            at = next((j for j, node in enumerate(nodes) if node[0] == ref), None)
            if at is None:
                _parse_error("couldn't find: &" + ref, rules, where)
            pos = at
            continue
        if pending_rel is None:
            _parse_error("missing char (=,;<&) : " + rules, rules, where)
        rel = pending_rel
        pending_rel = None
        # a relation to a string that is already ordered moves it
        old = next((j for j, node in enumerate(nodes) if node[0] == value), None)
        if old is not None:
            nodes.pop(old)
            if old <= pos:
                pos -= 1
        j = pos + 1
        while j < len(nodes) and nodes[j][1] > rel:
            j += 1
        nodes.insert(j, [value, rel])
        pos = j
    if reset_pending or pending_rel is not None:
        _parse_error("missing chars (=,;<&): " + rules[tokens[-1][2] + 1:], rules, len(rules))
    mapping = {}
    p = s = t = 0
    for text, rel in nodes:
        if rel == 0:
            p, s, t = p + 1, 0, 0
        elif rel == 1:
            s, t = s + 1, 0
        elif rel == 2:
            t += 1
        if p == 0:
            p = 1
        mapping[text] = ((p, s, t),)
    return _Table(mapping, rules)


@host_class("java.text.CollationElementIterator", final=True)
class CollationElementIterator(Object):
    NULLORDER = -1
    IGNORABLE = 0

    def __init__(self, table, text, decomposition):
        self._table, self._decomposition = table, decomposition
        self._set(text)

    def _set(self, text):
        self._text = text
        self._els = _elements(text, self._table.mapping, self._table.contractions, self._decomposition, self._table.decompose)
        self._pos = 0

    def next(self):
        if self._pos >= len(self._els):
            return NULLORDER
        order = _order(self._els[self._pos])
        self._pos += 1
        return order

    def previous(self):
        if self._pos <= 0:
            return NULLORDER
        self._pos -= 1
        return _order(self._els[self._pos])

    def reset(self):
        self._pos = 0

    def getOffset(self):
        return 0 if self._pos == 0 else min(len(self._text), self._pos)

    def setOffset(self, offset):
        self._pos = min(offset, len(self._els))

    def setText(self, text):
        self._set(text if isinstance(text, str) else str(text))

    def getMaxExpansion(self, order):
        return max(2 if len(e) > 1 else 1 for e in self._table.mapping.values()) if False else 1

    @staticmethod
    def primaryOrder(order):
        return (order >> 16) & 0xFFFF

    @staticmethod
    def secondaryOrder(order):
        return (order >> 8) & 0xFF

    @staticmethod
    def tertiaryOrder(order):
        return order & 0xFF


@host_class("java.text.CollationKey", abstract=True, interfaces=("java.lang.Comparable",))
class CollationKey(Object):
    def __init__(self, source, key):
        self._source, self._key = source, key

    def getSourceString(self):
        return self._source

    def compareTo(self, other):
        a, b = self._key, check_nonnull(other)._key
        return (a > b) - (a < b)

    def equals(self, other):
        return 1 if isinstance(other, CollationKey) and other._key == self._key else 0

    def hashCode(self):
        h = 0
        for c in self._key:
            h = (31 * h + c) & 0xFFFFFFFF
        return runtime.wrap32(h)

    def toByteArray(self):
        out = []
        for c in self._key:
            out.append(((c >> 8) & 0xFF) - (256 if (c >> 8) & 0x80 else 0))
            out.append((c & 0xFF) - (256 if c & 0x80 else 0))
        out.extend([0, 0])
        from .jutil import to_array
        return to_array(out, "[B")


RuleBasedCollationKey = host_class("java.text.RuleBasedCollationKey", final=True)(type("RuleBasedCollationKey", (CollationKey,), {}))


@host_class("java.text.Collator", interfaces=("java.util.Comparator", "java.lang.Cloneable"))
class Collator(Object):
    PRIMARY, SECONDARY, TERTIARY, IDENTICAL = 0, 1, 2, 3
    NO_DECOMPOSITION, CANONICAL_DECOMPOSITION, FULL_DECOMPOSITION = 0, 1, 2

    def __init__(self, table=None):
        self._table = table if table is not None else default_table()
        self._strength = 2
        self._decomposition = 0

    @staticmethod
    def getInstance(locale=None):
        return RuleBasedCollator(None)

    @staticmethod
    def getAvailableLocales():
        from .jutil import to_array
        from .api import lookup_host
        return to_array([lookup_host("java.util.Locale").py.US], "[Ljava/util/Locale;")

    def setStrength(self, strength):
        if strength not in (0, 1, 2, 3):
            runtime.throw_new("java.lang.IllegalArgumentException", "Incorrect comparison level.")
        self._strength = strength

    def getStrength(self):
        return self._strength

    def setDecomposition(self, mode):
        if mode not in (0, 1, 2):
            runtime.throw_new("java.lang.IllegalArgumentException", "Wrong decomposition mode.")
        self._decomposition = mode

    def getDecomposition(self):
        return self._decomposition

    def getRules(self):
        return jstr(self._table.rules)

    def getCollationElementIterator(self, text):
        if not isinstance(text, str):
            chars = []
            c = text.first()
            while c != "￿":
                chars.append(c)
                c = text.next()
            text = "".join(chars)
        return CollationElementIterator(self._table, check_nonnull(text), self._decomposition)

    def compare(self, a, b):
        if not isinstance(a, str) or not isinstance(b, str):
            if a is None or b is None:
                runtime.npe()
            if not isinstance(a, str):
                runtime.throw_new("java.lang.ClassCastException", "%s cannot be cast to java.lang.String" % runtime.class_of(a).getName())
            runtime.throw_new("java.lang.ClassCastException", "%s cannot be cast to java.lang.String" % runtime.class_of(b).getName())
        return self._compare(a, b)

    def _compare(self, source, target):
        t = self._table
        src = [_order(e) for e in _elements(source, t.mapping, t.contractions, self._decomposition, t.decompose)]
        tgt = [_order(e) for e in _elements(target, t.mapping, t.contractions, self._decomposition, t.decompose)]
        strength = self._strength
        result = 0
        check_sec_ter = strength >= 1
        check_tertiary = strength >= 2
        si = ti = 0
        gets = gett = True
        s_order = t_order = 0
        while True:
            if gets:
                s_order = src[si] if si < len(src) else NULLORDER
                si += 1
            else:
                gets = True
            if gett:
                t_order = tgt[ti] if ti < len(tgt) else NULLORDER
                ti += 1
            else:
                gett = True
            if s_order == NULLORDER or t_order == NULLORDER:
                break
            ps = CollationElementIterator.primaryOrder(s_order)
            pt = CollationElementIterator.primaryOrder(t_order)
            if s_order == t_order:
                continue
            if ps != pt:
                if s_order == 0:
                    gett = False
                    continue
                if t_order == 0:
                    gets = False
                    continue
                if ps == 0:
                    if check_sec_ter:
                        result = 1
                        check_sec_ter = False
                    gett = False
                elif pt == 0:
                    if check_sec_ter:
                        result = -1
                        check_sec_ter = False
                    gets = False
                else:
                    return -1 if ps < pt else 1
            else:
                if check_sec_ter:
                    ss = CollationElementIterator.secondaryOrder(s_order)
                    st = CollationElementIterator.secondaryOrder(t_order)
                    if ss != st:
                        result = -1 if ss < st else 1
                        check_sec_ter = False
                    elif check_tertiary:
                        ts = CollationElementIterator.tertiaryOrder(s_order)
                        tt = CollationElementIterator.tertiaryOrder(t_order)
                        if ts != tt:
                            result = -1 if ts < tt else 1
                            check_tertiary = False
        if s_order != NULLORDER:
            while True:
                if CollationElementIterator.primaryOrder(s_order) != 0:
                    return 1
                elif CollationElementIterator.secondaryOrder(s_order) != 0:
                    if check_sec_ter:
                        result = 1
                        check_sec_ter = False
                s_order = src[si] if si < len(src) else NULLORDER
                si += 1
                if s_order == NULLORDER:
                    break
        elif t_order != NULLORDER:
            while True:
                if CollationElementIterator.primaryOrder(t_order) != 0:
                    return -1
                elif CollationElementIterator.secondaryOrder(t_order) != 0:
                    if check_sec_ter:
                        result = -1
                        check_sec_ter = False
                t_order = tgt[ti] if ti < len(tgt) else NULLORDER
                ti += 1
                if t_order == NULLORDER:
                    break
        if result == 0 and strength == 3:
            a, b = source, target
            if self._decomposition == 1:
                a, b = unicodedata.normalize("NFD", a), unicodedata.normalize("NFD", b)
            elif self._decomposition == 2:
                a, b = unicodedata.normalize("NFKD", a), unicodedata.normalize("NFKD", b)
            result = _java_compare(a, b)
        return result

    def equals(self, a, b=_MISSING):
        if b is _MISSING:
            return 1 if isinstance(a, Collator) and a._table.rules == self._table.rules and a._strength == self._strength \
                and a._decomposition == self._decomposition else 0
        return 1 if self._compare(a, b) == 0 else 0

    def hashCode(self):
        from .jfunc import string_hash
        return string_hash(self._table.rules)

    def getCollationKey(self, source):
        if source is None:
            return None
        t = self._table
        els = _elements(source, t.mapping, t.contractions, self._decomposition, t.decompose)
        primary = [p for p, s, tt in els if p]
        key = list(primary)
        if self._strength >= 1:
            key.append(0)
            key.extend(s for p, s, tt in els if s)
        if self._strength >= 2:
            key.append(0)
            key.extend(tt for p, s, tt in els if tt)
        return RuleBasedCollationKey(source, key)

    def clone(self):
        c = RuleBasedCollator(self._table)
        c._strength, c._decomposition = self._strength, self._decomposition
        return c



@host_class("java.text.RuleBasedCollator")
class RuleBasedCollator(Collator):
    def __init__(self, table=None):
        Collator.__init__(self, table)

    @jmethod("<init>", "(Ljava/lang/String;)V")
    def _init(self, rules):
        Collator.__init__(self, build_table(check_nonnull(rules)))
        self._table.rules = rules
