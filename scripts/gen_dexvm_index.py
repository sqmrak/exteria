#!/usr/bin/env python3
"""rewrites python/shim/dexvm/index.py: the java class names each library module of the dex runtime registers, so the
runtime can import a module the first time a program names one of its classes. run it after adding or moving a class
in a module other than jlang; tests/python/test_dexvm.py fails while the file is out of date"""

import importlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHIM = os.path.join(ROOT, "python", "shim")
LIBRARIES = ("jreflect", "jfunc", "jutil", "jmap", "jmisc", "jjson", "jref", "jtime", "jnet", "jnio", "jcoll", "jfiles", "jstream", "jtimeapi", "jextra", "jcrypto", "jtext2", "jnet2", "jio", "jloader", "jtext", "jconc", "jnum", "jinvoke", "jzip", "jindy", "jmore", "jmore2", "jsec", "jcert", "jkeys", "jtimefmt", "jchrono", "jbidi", "jcollate")


def collect():
    sys.path.insert(0, SHIM)
    from dexvm import api
    for name in LIBRARIES:
        importlib.import_module("dexvm." + name)
    table = {}
    for name in api.host_names():
        entry = api.lookup_host(name)
        module = entry.module.rsplit(".", 1)[-1] if entry.module else None
        if module in LIBRARIES:
            table[name] = module
    return table


def render(table):
    lines = ['"""the library module of each java class the dex runtime implements outside java.lang, generated by',
             'scripts/gen_dexvm_index.py: the runtime imports a module when a program first names one of its classes"""',
             "", "NAMES = {"]
    for name in sorted(table):
        lines.append('    "%s": "%s",' % (name, table[name]))
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render(collect())
    target = os.path.join(SHIM, "dexvm", "index.py")
    if "--check" in sys.argv:
        with open(target) as handle:
            if handle.read() != text:
                print("dexvm/index.py is out of date, run scripts/gen_dexvm_index.py", file=sys.stderr)
                sys.exit(1)
    else:
        with open(target, "w") as handle:
            handle.write(text)
        print("wrote %s" % target)
